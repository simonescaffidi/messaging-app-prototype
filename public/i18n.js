  function detectLang() {
    const saved = localStorage.getItem("app_lang");
    if (saved && DICTS[saved]) return saved;
    const nav = (navigator.language || "it").slice(0, 2).toLowerCase();
    return DICTS[nav] ? nav : "it";
  }

  let current = detectLang();

  function t(key) {
    return (DICTS[current] && DICTS[current][key]) || DICTS.it[key] || key;
  }

  function setLang(lang) {
    if (!DICTS[lang]) return;
    current = lang;
    localStorage.setItem("app_lang", lang);
    apply();
  }

  function apply() {
    document.documentElement.lang = current;
    document.documentElement.dir = RTL_LANGS.includes(current) ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
  }

  return { LANGS, LANG_NAMES, t, setLang, apply, get current() { return current; } };
